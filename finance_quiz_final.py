def start_quiz(difficulty, num_questions):
    bank = QUESTIONS[difficulty]
    num_q = min(int(num_questions), len(bank))
    selected = random.sample(bank, num_q)

    state = {
        "difficulty": difficulty,
        "questions": selected,
        "current_idx": 0,
        "score": 0,
        "wrong_answers": [],
        "points_per_q": POINTS_PER_DIFFICULTY[difficulty],
    }

    first_q = selected[0]
    q_title = f"### Question 1 of {num_q} [{first_q['topic']}]"
    q_text = first_q["question"]

    audio_text = f"Question 1. Topic: {first_q['topic']}. {first_q['question']} Options are: " + " ".join(first_q["options"])
    audio_file = generate_audio(audio_text)

    return (
        gr.update(visible=False),                                     # setup_box
        gr.update(visible=True),                                      # quiz_box
        gr.update(visible=False),                                     # result_box
        state,                                                        # state
        q_title,                                                      # question_title
        q_text,                                                       # question_text
        gr.Radio(choices=first_q["options"], value=None, label="Choose an answer"), # options_radio
        "",                                                           # feedback_markdown
        audio_file,                                                   # audio_player
        gr.update(visible=True),                                      # submit_btn
        gr.update(visible=False)                                      # next_btn
    )

def submit_answer(user_choice, state):
    if not user_choice:
        return (
            state,
            "⚠️ Please select an answer before submitting.",
            None,
            gr.update(visible=True),
            gr.update(visible=False)
        )

    current_q = state["questions"][state["current_idx"]]
    chosen_letter = user_choice.strip()[0].upper()
    points = state["points_per_q"]

    if chosen_letter == current_q["answer"]:
        state["score"] += points
        feedback = f"✅ **Correct!** (+{points} point{'s' if points != 1 else ''})\n\n💡 *Explanation:* {current_q['explanation']}"
        speech_feedback = f"Correct! {current_q['explanation']}"
    else:
        state["wrong_answers"].append(current_q)
        feedback = f"❌ **Not quite.** The correct answer was **{current_q['answer']}**.\n\n💡 *Explanation:* {current_q['explanation']}"
        speech_feedback = f"Not quite. The correct answer was {current_q['answer']}. {current_q['explanation']}"

    audio_file = generate_audio(speech_feedback)

    return (
        state,
        feedback,
        audio_file,
        gr.update(visible=False), # Hide Submit
        gr.update(visible=True)   # Show Next
    )

def next_question(state):
    state["current_idx"] += 1

    # Check if quiz ended
    if state["current_idx"] >= len(state["questions"]):
        num_q = len(state["questions"])
        total_possible = num_q * state["points_per_q"]
        score = state["score"]
        pct = (score / total_possible) * 100 if total_possible else 0

        if pct == 100:
            msg = "🌟 **Perfect score!** You're a finance superstar!"
        elif pct >= 70:
            msg = "👍 **Great job!** You know your money basics well."
        elif pct >= 40:
            msg = "🙂 **Good try!** A little more practice and you'll master this."
        else:
            msg = "📚 **Keep learning** — review the explanations and try again!"

        results_md = f"## 🏆 Quiz Completed!\n\n"
        results_md += f"**Final Score:** {score} / {total_possible} points ({pct:.0f}%)\n\n{msg}\n\n"

        if state["wrong_answers"]:
            results_md += "### Topics to Review:\n"
            for q in state["wrong_answers"]:
                results_md += f"- **{q['topic']}**: {q['question']}\n"

        speech_msg = f"Quiz complete! Your final score is {score} out of {total_possible} points."
        audio_file = generate_audio(speech_msg)

        return (
            gr.update(visible=False), # quiz_box
            gr.update(visible=True),  # result_box
            state,
            "",                       # question_title
            "",                       # question_text
            gr.Radio(choices=[], value=None), # options_radio
            "",                       # feedback_markdown
            results_md,               # results_markdown
            audio_file,
            gr.update(visible=False), # submit_btn
            gr.update(visible=False)  # next_btn
        )

    # Load Next Question
    q = state["questions"][state["current_idx"]]
    q_title = f"### Question {state['current_idx'] + 1} of {len(state['questions'])} [{q['topic']}]"
    q_text = q["question"]

    audio_text = f"Question {state['current_idx'] + 1}. Topic: {q['topic']}. {q['question']} Options are: " + " ".join(q["options"])
    audio_file = generate_audio(audio_text)

    return (
        gr.update(visible=True),  # quiz_box
        gr.update(visible=False), # result_box
        state,
        q_title,
        q_text,
        gr.Radio(choices=q["options"], value=None, label="Choose an answer"),
        "",                       # Clear feedback
        "",                       # Clear results
        audio_file,
        gr.update(visible=True),  # Show Submit
        gr.update(visible=False)  # Hide Next
    )

def reset_quiz():
    return (
        gr.update(visible=True),  # setup_box
        gr.update(visible=False), # quiz_box
        gr.update(visible=False), # result_box
        {}
    )


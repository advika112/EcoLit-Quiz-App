    quiz_state = gr.State({})

    gr.Markdown("# 💰 Finance & Economics Quiz")
    gr.Markdown("Learn about saving, loans, profit, inflation, scarcity, social media & smart money habits!")

    # Audio Player
    audio_player = gr.Audio(label="🔊 Audio Assistant", autoplay=True)

    # --- STEP 1: SETUP INTERFACE ---
    with gr.Column() as setup_box:
        gr.Markdown("### ⚙️ Quiz Settings")
        difficulty_dropdown = gr.Dropdown(
            choices=["easy", "medium", "hard"],
            value="easy",
            label="Select Difficulty Level"
        )
        num_questions_slider = gr.Slider(
            minimum=1,
            maximum=8,
            value=5,
            step=1,
            label="Number of Questions"
        )
        start_btn = gr.Button("🚀 Start Quiz", variant="primary")

    # --- STEP 2: QUIZ QUESTION INTERFACE ---
    with gr.Column(visible=False) as quiz_box:
        question_title = gr.Markdown()
        question_text = gr.Markdown()
        options_radio = gr.Radio(choices=[], label="Choose an answer")

        submit_btn = gr.Button("Submit Answer", variant="primary")
        feedback_markdown = gr.Markdown()
        next_btn = gr.Button("Next Question ➔", visible=False)

    # --- STEP 3: RESULTS INTERFACE ---
    with gr.Column(visible=False) as result_box:
        results_markdown = gr.Markdown()
        restart_btn = gr.Button("🔄 Try Another Quiz", variant="primary")

    # ---------------------------------------------------------------------------
    # EVENT CONNECTIONS
    # ---------------------------------------------------------------------------
    start_btn.click(
        fn=start_quiz,
        inputs=[difficulty_dropdown, num_questions_slider],
        outputs=[
            setup_box, quiz_box, result_box, quiz_state,
            question_title, question_text, options_radio,
            feedback_markdown, audio_player, submit_btn, next_btn
        ]
    )

    submit_btn.click(
        fn=submit_answer,
        inputs=[options_radio, quiz_state],
        outputs=[quiz_state, feedback_markdown, audio_player, submit_btn, next_btn]
    )

    next_btn.click(
        fn=next_question,
        inputs=[quiz_state],
        outputs=[
            quiz_box, result_box, quiz_state,
            question_title, question_text, options_radio,
            feedback_markdown, results_markdown, audio_player,
            submit_btn, next_btn
        ]
    )

    restart_btn.click(
        fn=reset_quiz,
        inputs=[],
        outputs=[setup_box, quiz_box, result_box, quiz_state]
    )


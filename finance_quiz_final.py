POINTS_PER_DIFFICULTY = {"easy": 1, "medium": 2, "hard": 3}

# Helper function for Text-to-Speech audio generation
def generate_audio(text):
    if not text or not text.strip():
        return None
    try:
        filename = "speech_output.mp3"
        tts = gTTS(text=text, lang="en", slow=False)
        tts.save(filename)
        return filename
    except Exception:
        return None

